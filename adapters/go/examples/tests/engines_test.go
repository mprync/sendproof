package tests

import (
	"crypto/rand"
	"database/sql"
	"encoding/hex"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"testing"

	"github.com/test-bench/test-bench/adapters/go/examples/fixture"
)

// engine is one database the provider tests run against. SQLite always runs.
// PostgreSQL, MySQL and SQL Server run when BENCH_POSTGRES_URL, BENCH_MYSQL_URL
// and BENCH_SQLSERVER_URL point at a disposable server; each test then gets a
// fresh database of its own, dropped afterwards.
type engine struct {
	name     string
	variable string
	// ph returns the bind placeholder for a 1-based position.
	ph func(int) string
	// text is the column type for short strings.
	text string
	// autoKey declares a generated integer primary key column named id.
	autoKey string
}

var allEngines = []engine{
	{name: "sqlite", ph: func(int) string { return "?" }, text: "TEXT", autoKey: "id INTEGER PRIMARY KEY"},
	{name: "postgresql", variable: "BENCH_POSTGRES_URL", ph: func(n int) string { return "$" + strconv.Itoa(n) }, text: "text", autoKey: "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"},
	{name: "mysql", variable: "BENCH_MYSQL_URL", ph: func(int) string { return "?" }, text: "VARCHAR(191)", autoKey: "id BIGINT AUTO_INCREMENT PRIMARY KEY"},
	{name: "sqlserver", variable: "BENCH_SQLSERVER_URL", ph: func(n int) string { return "@p" + strconv.Itoa(n) }, text: "NVARCHAR(191)", autoKey: "id BIGINT IDENTITY(1,1) PRIMARY KEY"},
}

// eachEngine runs body once per available engine.
func eachEngine(t *testing.T, body func(t *testing.T, e engine, pool *sql.DB)) {
	t.Helper()
	for _, e := range allEngines {
		t.Run(e.name, func(t *testing.T) {
			pool := openEngine(t, e)
			body(t, e, pool)
		})
	}
}

// openEngine connects to a fresh database of the engine.
func openEngine(t *testing.T, e engine) *sql.DB {
	t.Helper()
	database := fixture.Database{Engine: e.name, Directory: t.TempDir()}
	if e.variable != "" {
		server := os.Getenv(e.variable)
		if server == "" {
			t.Skipf("set %s to run the %s tests", e.variable, e.name)
		}
		database.URL = freshDatabase(t, e, server)
	}
	driver, dsn, err := fixture.DataSource(database)
	if err != nil {
		t.Fatal(err)
	}
	pool, err := sql.Open(driver, dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { pool.Close() })
	if err := pool.Ping(); err != nil {
		t.Fatal(err)
	}
	return pool
}

// freshDatabase creates a database with a random name on the server and drops it
// when the test ends.
func freshDatabase(t *testing.T, e engine, server string) string {
	t.Helper()
	suffix := make([]byte, 6)
	_, _ = rand.Read(suffix)
	name := "tb_go_" + hex.EncodeToString(suffix)
	admin := openURL(t, e, server)
	if _, err := admin.Exec("CREATE DATABASE " + name); err != nil {
		t.Fatal(err)
	}
	target, _ := url.Parse(server)
	target.Path = "/" + name
	t.Cleanup(func() {
		drop := "DROP DATABASE " + name
		switch e.name {
		case "postgresql":
			drop += " WITH (FORCE)"
		case "sqlserver":
			_, _ = admin.Exec("ALTER DATABASE " + name + " SET SINGLE_USER WITH ROLLBACK IMMEDIATE")
		}
		if _, err := admin.Exec(drop); err != nil {
			t.Errorf("drop %s: %v", name, err)
		}
		admin.Close()
	})
	return target.String()
}

func openURL(t *testing.T, e engine, server string) *sql.DB {
	t.Helper()
	driver, dsn, err := fixture.DataSource(fixture.Database{Engine: e.name, URL: server, Directory: filepath.Join(t.TempDir())})
	if err != nil {
		t.Fatal(err)
	}
	pool, err := sql.Open(driver, dsn)
	if err != nil {
		t.Fatal(err)
	}
	return pool
}

// exec runs setup statements on the pool, outside Test Bench.
func exec(t *testing.T, pool *sql.DB, statements ...string) {
	t.Helper()
	for _, statement := range statements {
		if _, err := pool.Exec(statement); err != nil {
			t.Fatalf("%s: %v", statement, err)
		}
	}
}
