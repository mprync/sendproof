/**
 * Regenerates sendproof-core/src/stores/tables.rs from the shared classification tables in
 * spec/data-stores/.
 *
 * The tables are embedded unchanged, as the text of each spec file, so the published crate needs no
 * file outside src/. The core's unit test `embedded_tables_match_the_spec` fails when this copy and
 * the spec differ; run `node adapters/rust/scripts/embed-store-tables.mjs` to bring them back in line.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const spec = new URL('../../../spec/data-stores/', import.meta.url);
const output = new URL('../sendproof-core/src/stores/tables.rs', import.meta.url);

const lines = [
  '//! Generated by adapters/rust/scripts/embed-store-tables.mjs from spec/data-stores/. Do not edit by hand.',
  '//!',
  '//! Each constant is the text of one shared classification table, embedded unchanged. A unit test',
  '//! fails when a copy differs from the spec file.',
  '',
];
for (const store of ['redis', 'mongodb', 'dynamodb']) {
  const text = readFileSync(new URL(`${store}.json`, spec), 'utf8');
  if (text.includes('"#')) throw new Error(`${store}.json contains a raw-string terminator`);
  lines.push(`/// The shared ${store} classification table, \`spec/data-stores/${store}.json\`.`, `pub const ${store.toUpperCase()}: &str = r#"${text}"#;`, '');
}
writeFileSync(output, lines.join('\n'));
