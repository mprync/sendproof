/**
 * Regenerates core/src/stores/tables.ts from the shared classification tables in spec/data-stores/.
 *
 * The tables are embedded unchanged so the published package needs no file outside dist. The unit
 * test "embedded data-store tables match spec/data-stores" fails when the copy and the spec differ;
 * run this script (`npm run embed-store-tables --workspace @sendproof/core`) to bring them back in line.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const spec = new URL('../../../../spec/data-stores/', import.meta.url);
const output = new URL('../src/stores/tables.ts', import.meta.url);
const tables = ['redis', 'mongodb', 'dynamodb'].map(store => [store, JSON.parse(readFileSync(new URL(`${store}.json`, spec), 'utf8'))]);

const lines = [
  '// Generated by core/scripts/embed-store-tables.mjs from spec/data-stores/. Do not edit by hand.',
  '// A unit test fails when this copy differs from the spec tables.',
  '',
  ...tables.flatMap(([store, table]) => [
    `/** The shared ${store} classification table, embedded unchanged from spec/data-stores/${store}.json. */`,
    `export const ${store}Table = ${JSON.stringify(table, null, 2)} as const;`,
    '',
  ]),
];
writeFileSync(output, lines.join('\n'));
