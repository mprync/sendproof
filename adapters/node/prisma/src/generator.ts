#!/usr/bin/env node
/**
 * A Prisma generator that writes the row identity metadata used by `PrismaPreview`.
 *
 * Add it beside the client generator and run `prisma generate`:
 *
 * ```prisma
 * generator testBench {
 *   provider = "test-bench-prisma-generator"
 *   output   = "./generated/test-bench"
 * }
 * ```
 *
 * Prisma starts generators as child processes and exchanges newline-delimited JSON-RPC 2.0
 * messages: requests arrive on stdin and responses are written to stderr. This file speaks
 * that protocol directly so the package needs no generator runtime dependency.
 */
import { realpathSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';
import { fromDmmf, type DmmfModel, type PrismaModelMetadata } from './metadata.js';

interface RpcRequest {
  jsonrpc: '2.0';
  id: number;
  method: string;
  params?: unknown;
}

interface GenerateParams {
  generator: { output?: { value?: string | null } | null };
  dmmf: { datamodel: { models: DmmfModel[] } };
}

/** Render the generated ES module and its declaration file. */
export function renderModule(metadata: PrismaModelMetadata): { js: string; dts: string } {
  const banner = '// Generated by @test-bench/prisma from the Prisma schema. Do not edit.\n';
  return {
    js: banner + 'export const models = ' + JSON.stringify(metadata, null, 2) + ';\nexport default models;\n',
    dts: banner + "import type { PrismaModelMetadata } from '@test-bench/prisma';\n"
      + 'export declare const models: PrismaModelMetadata;\nexport default models;\n',
  };
}

/** Write the metadata module for the models in a DMMF document. */
export async function generate(params: GenerateParams): Promise<string> {
  const output = params.generator.output?.value;
  if (!output) throw new Error('Set output on the test-bench-prisma-generator block.');
  const { js, dts } = renderModule(fromDmmf(params.dmmf.datamodel.models));
  await mkdir(output, { recursive: true });
  await writeFile(join(output, 'index.js'), js);
  await writeFile(join(output, 'index.d.ts'), dts);
  return output;
}

function respond(message: object): void {
  process.stderr.write(JSON.stringify({ jsonrpc: '2.0', ...message }) + '\n');
}

async function handle(request: RpcRequest): Promise<void> {
  try {
    switch (request.method) {
      case 'getManifest':
        respond({ id: request.id, result: { manifest: {
          prettyName: 'Test Bench model keys',
          defaultOutput: './generated/test-bench',
          requiresEngines: [],
        } } });
        return;
      case 'generate':
        await generate(request.params as GenerateParams);
        respond({ id: request.id, result: null });
        return;
      default:
        respond({ id: request.id, error: { code: -32601, message: 'Method not found: ' + request.method } });
    }
  } catch (error) {
    const failure = error instanceof Error ? error : new Error(String(error));
    respond({ id: request.id, error: { code: -32000, message: failure.message, data: { stack: failure.stack } } });
  }
}

/** Serve Prisma's generator protocol until stdin closes. */
export function serve(): void {
  const pending: Promise<void>[] = [];
  createInterface({ input: process.stdin, crlfDelay: Infinity })
    .on('line', line => {
      if (!line.trim()) return;
      let request: RpcRequest;
      try {
        request = JSON.parse(line) as RpcRequest;
      } catch {
        process.stderr.write('test-bench-prisma-generator: ignored a malformed message\n');
        return;
      }
      pending.push(handle(request));
    })
    .on('close', () => { void Promise.all(pending).then(() => process.exit(0)); });
}

function isMain(): boolean {
  try {
    return process.argv[1] !== undefined && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

if (isMain()) {
  if (process.env.PRISMA_GENERATOR_INVOCATION) serve();
  else process.stdout.write('test-bench-prisma-generator runs from `prisma generate`. Add a generator block to schema.prisma.\n');
}
