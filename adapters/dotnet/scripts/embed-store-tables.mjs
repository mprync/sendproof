/**
 * Regenerates Sendproof.AspNetCore/Stores/StoreTables.g.cs from the shared classification tables in
 * spec/data-stores/.
 *
 * The tables are embedded unchanged, as raw JSON text, so the published package needs no file outside
 * its assembly. The unit test "EmbeddedTablesMatchTheSpec" fails when the copy and the spec differ; run
 * this script (`node adapters/dotnet/scripts/embed-store-tables.mjs`) to bring them back in line.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const spec = new URL('../../../spec/data-stores/', import.meta.url);
const output = new URL('../Sendproof.AspNetCore/Stores/StoreTables.g.cs', import.meta.url);
const name = store => store[0].toUpperCase() + store.slice(1);

const lines = [
  '// <auto-generated>',
  '// Generated by adapters/dotnet/scripts/embed-store-tables.mjs from spec/data-stores/. Do not edit by hand.',
  '// A unit test fails when this copy differs from the spec tables.',
  '// </auto-generated>',
  '',
  'namespace Sendproof.AspNetCore;',
  '',
  'internal static class EmbeddedStoreTables',
  '{',
];
for (const store of ['redis', 'mongodb', 'dynamodb', 'cassandra', 'elasticsearch', 'cosmosdb', 'firestore']) {
  const json = JSON.stringify(JSON.parse(readFileSync(new URL(`${store}.json`, spec), 'utf8')), null, 2);
  if (json.includes('"""""')) throw new Error(`${store}.json contains a raw-string delimiter`);
  lines.push(
    `    /// <summary>The shared ${store} classification table, embedded unchanged from spec/data-stores/${store}.json.</summary>`,
    `    internal const string ${name(store)} = """""`,
    json,
    '"""""',
    '        ;',
    '',
  );
}
lines.push('}', '');
writeFileSync(output, lines.join('\n'));
