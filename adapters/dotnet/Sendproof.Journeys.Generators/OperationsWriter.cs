using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Sendproof.Journeys.Generators;

/// <summary>
/// Writes the operations catalog: one nested class per group (<c>StoreOperations.Orders</c>), one typed
/// <c>JourneyOperation</c> per operation with its request class, and a <c>JourneySource</c> per journey class.
/// </summary>
internal static class OperationsWriter
{
    public static void Write(SourceProductionContext context, ImmutableArray<EndpointInfo> endpoints,
        ImmutableArray<JourneyClassInfo> journeys, GeneratorSettings settings)
    {
        if (!settings.Enabled)
        {
            return;
        }

        var members = new Dictionary<(string? Group, string Member), EndpointInfo>();
        foreach (var endpoint in endpoints.OrderBy(endpoint => endpoint.Location.FilePath).ThenBy(endpoint => endpoint.Location.Span.Start))
        {
            if (endpoint.Name is null)
            {
                context.ReportDiagnostic(Diagnostic.Create(GeneratorDiagnostics.Unnamed, endpoint.Location.ToLocation(),
                    endpoint.Method, endpoint.Route, endpoint.ImpliedName));
            }

            var operationName = endpoint.Name ?? endpoint.ImpliedName;
            var key = Names.Split(operationName);
            if (members.TryGetValue(key, out var existing))
            {
                // The same name mapped twice (in two branches, say) is one operation; two names that collide are not.
                if ((existing.Name ?? existing.ImpliedName) != operationName)
                {
                    context.ReportDiagnostic(Diagnostic.Create(GeneratorDiagnostics.Duplicate, endpoint.Location.ToLocation(),
                        existing.Name ?? existing.ImpliedName, operationName, key.Group is null ? key.Member : $"{key.Group}.{key.Member}"));
                }

                continue;
            }

            members[key] = endpoint;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>").AppendLine("#nullable enable").AppendLine($"namespace {settings.Namespace};").AppendLine();
        source.AppendLine("/// <summary>The app's operations, generated by Sendproof.Journeys from its endpoint mappings, for typed journeys.</summary>");
        source.AppendLine($"internal static partial class {settings.ClassName}").AppendLine("{");
        foreach (var group in members.GroupBy(pair => pair.Key.Group).OrderBy(group => group.Key ?? ""))
        {
            var indent = group.Key is null ? "    " : "        ";
            if (group.Key is not null)
            {
                source.AppendLine($"    /// <summary>The {group.Key} operations.</summary>");
                source.AppendLine($"    internal static class {group.Key}").AppendLine("    {");
            }

            var first = true;
            foreach (var pair in group.OrderBy(pair => pair.Key.Member))
            {
                if (!first)
                {
                    source.AppendLine();
                }

                WriteOperation(source, indent, pair.Key.Member, pair.Value);
                first = false;
            }

            if (group.Key is not null)
            {
                source.AppendLine("    }").AppendLine();
            }
        }

        source.AppendLine("}");
        context.AddSource($"{settings.ClassName}.g.cs", source.ToString());

        if (journeys.Length > 0)
        {
            var sources = new StringBuilder("// <auto-generated/>\n");
            foreach (var journey in journeys.Distinct().OrderBy(journey => journey.Type))
            {
                sources.AppendLine($"[assembly: global::Sendproof.Journeys.JourneySource(typeof({journey.Type}), {Literal(Relative(journey.FilePath, settings.ProjectDirectory))})]");
            }

            context.AddSource("JourneySources.g.cs", sources.ToString());
        }
    }

    private static void WriteOperation(StringBuilder source, string indent, string member, EndpointInfo endpoint)
    {
        var name = endpoint.Name ?? endpoint.ImpliedName;
        source.AppendLine($"{indent}/// <summary><c>{endpoint.Method} {Escape(endpoint.Route)}</c>, operation <c>{Escape(name)}</c>.</summary>");
        source.AppendLine($"{indent}internal static readonly global::Sendproof.Journeys.JourneyOperation<{member}Request, {endpoint.Response}> {member} = new({Literal(name)}, \"{endpoint.Method}\");");
        source.AppendLine();
        source.AppendLine($"{indent}/// <summary>The parameters and body of <see cref=\"{member}\"/>.</summary>");
        source.AppendLine($"{indent}internal sealed class {member}Request").AppendLine($"{indent}{{");
        foreach (var parameter in endpoint.Parameters)
        {
            var attribute = parameter.Source == "FromBody" ? "FromBody" : $"{parameter.Source}(Name = {Literal(parameter.Name)})";
            var initializer = parameter.NeedsValue ? " = default!;" : "";
            source.AppendLine($"{indent}    [global::Microsoft.AspNetCore.Mvc.{attribute}] public {parameter.Type} {parameter.Property} {{ get; set; }}{initializer}");
        }

        source.AppendLine($"{indent}}}");
    }

    private static string Relative(string path, string projectDirectory)
    {
        var relative = projectDirectory.Length > 0 && path.StartsWith(projectDirectory) ? path.Substring(projectDirectory.Length) : System.IO.Path.GetFileName(path);
        return relative.Replace('\\', '/').TrimStart('/');
    }

    private static string Literal(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
