#!/usr/bin/env python3
"""Regenerate ``core/src/sendproof_core/stores/tables.py`` from ``spec/data-stores/*.json``.

The shared classification tables are embedded unchanged so that the published wheel needs no file
outside the package. ``core/tests/test_stores.py`` fails when the embedded copy differs from the
spec, so run this script (``python adapters/python/scripts/embed_store_tables.py``) whenever the
spec tables change.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SPEC = ROOT / "spec" / "data-stores"
OUTPUT = Path(__file__).resolve().parents[1] / "core" / "src" / "sendproof_core" / "stores" / "tables.py"
STORES = ("redis", "mongodb", "dynamodb", "cassandra", "elasticsearch", "cosmosdb", "firestore")


def main() -> int:
    lines = [
        '"""The shared write-classification tables of spec/data-stores/, embedded unchanged.',
        "",
        "Generated by ``adapters/python/scripts/embed_store_tables.py``. Do not edit by hand: a unit",
        "test fails when this copy differs from the spec tables.",
        '"""',
        "",
        "import json",
        "",
    ]
    for store in STORES:
        table = json.loads((SPEC / f"{store}.json").read_text(encoding="utf-8"))
        text = json.dumps(table, indent=2, ensure_ascii=False)
        lines += [f"#: The shared {store} table, embedded from spec/data-stores/{store}.json.",
                  f"{store.upper()}_TABLE = json.loads(r'''{text}''')", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
