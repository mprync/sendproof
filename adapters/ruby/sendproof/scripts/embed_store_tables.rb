#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates lib/sendproof/stores/tables.rb from the shared classification tables in spec/data-stores/.
#
# The tables are embedded unchanged so the published gem needs no file outside lib/. The unit test
# "embedded data-store tables match spec/data-stores" fails when the copy and the spec differ; run
# this script (`rake stores:embed` from adapters/ruby) to bring them back in line. Never edit
# tables.rb by hand.

require "json"

SPEC = File.expand_path("../../../../spec/data-stores", __dir__)
OUTPUT = File.expand_path("../lib/sendproof/stores/tables.rb", __dir__)
STORES = %w[redis mongodb dynamodb].freeze

lines = [
  "# frozen_string_literal: true",
  "",
  "# Generated by scripts/embed_store_tables.rb from spec/data-stores/. Do not edit by hand.",
  "# A unit test fails when this copy differs from the spec tables.",
  "",
  "require \"json\"",
  "",
  "module Sendproof",
  "  module Stores",
  "    # The shared classification tables, embedded unchanged from spec/data-stores/*.json.",
  "    module Tables"
]
STORES.each do |store|
  table = JSON.pretty_generate(JSON.parse(File.read(File.join(SPEC, "#{store}.json"))))
  lines << "      # The #{store} table (spec/data-stores/#{store}.json)."
  lines << "      #{store.upcase} = JSON.parse(<<~'JSON').freeze"
  table.each_line { |line| lines << (line.strip.empty? ? "" : "        #{line.chomp}") }
  lines << "      JSON"
  lines << ""
end
lines.pop
lines << "    end"
lines << "  end"
lines << "end"
File.write(OUTPUT, lines.join("\n") + "\n")
puts "Wrote #{OUTPUT}"
