// Snapshots the running Treasury example into mocks/spec.js, so the mocks render the real
// OpenAPI document and real seeded data instead of hand-written samples.
//   node tools/mock-spec.mjs                      reads http://127.0.0.1:5189
//   BASE=http://127.0.0.1:5080 node tools/mock-spec.mjs
// It signs in as the seeded admin, reads the document and a few representative responses,
// and writes window.TB_SPEC (the OpenAPI document) and window.TB_SAMPLES (response bodies).
// Nothing is written to the API: every request is a GET apart from the sign-in.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const base = (process.env.BASE || 'http://127.0.0.1:5189').replace(/\/$/, '');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'mocks', 'spec.js');

async function get(path, cookie) {
  const response = await fetch(base + path, { headers: { Accept: 'application/json', ...(cookie ? { Cookie: cookie } : {}) } });
  if (!response.ok) throw new Error(`GET ${path} answered ${response.status}`);
  return response.json();
}

const spec = await get('/openapi/v1.json');
const login = await fetch(base + '/auth/login', {
  method: 'POST', headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ email: 'ada.admin@acme.dev', password: 'Demo123!' }),
});
if (!login.ok) throw new Error(`Sign-in answered ${login.status}`);
const cookie = login.headers.get('set-cookie').split(';')[0];

/** The first list operation whose path matches, read with the admin session. */
const pathOf = pattern => Object.keys(spec.paths).find(path => pattern.test(path));
const samples = {};
const read = async (name, path) => {
  if (!path) return;
  try { samples[name] = await get(path, cookie); } catch (error) { console.warn(`skipped ${name}: ${error.message}`); }
};

const payments = pathOf(/\/payments$/);
await read('paymentsPage', payments && `${payments}?pageSize=5&sort=-valueDate`);
await read('paymentsLarge', payments && `${payments}?pageSize=100`);
// The detail sample is an approved payment, so it has approvals and every nested object filled.
await read('approvedPage', payments && `${payments}?status=Approved&pageSize=1`);
const firstPayment = samples.approvedPage?.items?.[0] ?? samples.paymentsPage?.items?.[0] ?? samples.paymentsPage?.[0];
delete samples.approvedPage;
await read('payment', firstPayment && `${payments}/${firstPayment.id}`);
await read('accountsPage', pathOf(/\/accounts$/));
await read('counterpartiesPage', pathOf(/\/counterparties$/) && `${pathOf(/\/counterparties$/)}?pageSize=5`);

const banner = '// Generated by tools/mock-spec.mjs from the running Treasury example. Do not edit by hand.\n';
await writeFile(out, `${banner}window.TB_SPEC = ${JSON.stringify(spec, null, 1)};\nwindow.TB_SAMPLES = ${JSON.stringify(samples, null, 1)};\n`);
const operations = Object.values(spec.paths).flatMap(item => Object.keys(item).filter(key => /^(get|put|post|patch|delete)$/.test(key)));
console.log(`wrote ${out}: ${operations.length} operations, ${Object.keys(spec.components?.schemas ?? {}).length} schemas, samples ${Object.keys(samples).join(', ')}`);
